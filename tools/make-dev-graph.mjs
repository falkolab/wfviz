#!/usr/bin/env node
// Builds a development workflow script from the gate template and node specs.
//
//   node tools/make-dev-graph.mjs --n 6 --description "..." web-steady [other-slug ...]
//   -> workflows/dev-graph-6.js   (or --out <path>)
//
// Each slug names workflows/nodes/<slug>.mjs, whose default export is
// { code?, name, owns: string[], spec, lensA, lensB, risk?: 'low'|'high' (default high),
// ui?: { scenario } (adds the ui-check step) } (test is optional, unused by the gate).
// All nodes of one script run in parallel, so their owned paths must not overlap.
// The generated script = `export const meta` + `const NODES` + workflows/gate/gate-template.js.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const TEMPLATE = path.join(ROOT, 'workflows/gate/gate-template.js');
export const NODES_DIR = path.join(ROOT, 'workflows/nodes');

export const PHASES = [
  { title: 'Guide', detail: 'node guide in docs/guides/; rules for repeated finding categories' },
  { title: 'Implement', detail: 'one implementer per node, nodes in parallel' },
  { title: 'Test', detail: 'runs the full suite; counts parsed in code' },
  { title: 'Review', detail: 'two reviewers, full review once (also checks the guide), then diff-only verification (max 2)' },
  { title: 'Judge', detail: 'codex cli, always after the full review' },
  { title: 'Fix', detail: 'only judge-approved high/medium findings and failing tests' },
];

const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

export function checkNode(slug, node) {
  if (!SLUG.test(slug)) throw new Error(`node slug ${JSON.stringify(slug)} must be kebab-case`);
  for (const k of ['name', 'spec', 'lensA', 'lensB']) {
    if (typeof node?.[k] !== 'string' || !node[k].trim()) throw new Error(`node ${slug}: ${k} must be a non-empty string`);
  }
  if (!Array.isArray(node.owns) || !node.owns.length || node.owns.some((p) => typeof p !== 'string' || !p.trim())) {
    throw new Error(`node ${slug}: owns must be a non-empty array of paths`);
  }
  if (node.risk !== undefined && node.risk !== 'low' && node.risk !== 'high') throw new Error(`node ${slug}: risk must be "low" or "high"`);
  if (node.ui !== undefined && (typeof node.ui?.scenario !== 'string' || !node.ui.scenario.trim())) throw new Error(`node ${slug}: ui.scenario must be a non-empty string`);
}

const overlaps = (a, b) => a === b || a.startsWith(b.endsWith('/') ? b : `${b}/`) || b.startsWith(a.endsWith('/') ? a : `${a}/`);

export function buildScript({ n, description, nodes }) {
  if (!Number.isInteger(n) || n < 1) throw new Error('n must be a positive integer');
  if (typeof description !== 'string' || !description.trim()) throw new Error('description is required');
  const slugs = Object.keys(nodes);
  if (!slugs.length) throw new Error('at least one node is required');
  for (const s of slugs) checkNode(s, nodes[s]);
  for (let i = 0; i < slugs.length; i++) for (let j = i + 1; j < slugs.length; j++) {
    for (const p of nodes[slugs[i]].owns) for (const q of nodes[slugs[j]].owns) {
      if (overlaps(p, q)) throw new Error(`nodes ${slugs[i]} and ${slugs[j]} both own ${p} / ${q}: they would run in parallel`);
    }
  }
  const meta = { name: `wfviz-dev-graph-${n}`, description, phases: PHASES };
  const header = `// GENERATED by tools/make-dev-graph.mjs from workflows/gate/gate-template.js and\n// workflows/nodes/{${slugs.join(',')}}.mjs. Do not edit: change the template or the node file and regenerate.\n`;
  return `export const meta = ${JSON.stringify(meta, null, 2)}\n${header}const NODES = ${JSON.stringify(nodes, null, 2)}\n\n${fs.readFileSync(TEMPLATE, 'utf8')}`;
}

export async function loadNodes(slugs, dir = NODES_DIR) {
  const nodes = {};
  for (const s of slugs) {
    if (!SLUG.test(s)) throw new Error(`node slug ${JSON.stringify(s)} must be kebab-case`);
    nodes[s] = (await import(pathToFileURL(path.join(dir, `${s}.mjs`)).href)).default;
  }
  return nodes;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const argv = process.argv.slice(2);
  const opt = (k) => { const i = argv.indexOf(k); if (i < 0) return undefined; const v = argv[i + 1]; argv.splice(i, 2); return v; };
  const n = Number(opt('--n'));
  const description = opt('--description');
  const out = opt('--out') ?? path.join(ROOT, `workflows/dev-graph-${n}.js`);
  try {
    const text = buildScript({ n, description, nodes: await loadNodes(argv) });
    fs.writeFileSync(out, text);
    console.log(`wrote ${path.relative(ROOT, out)} (${argv.join(', ')})`);
  } catch (err) {
    console.error(`make-dev-graph: ${err.message}`);
    process.exit(2);
  }
}
