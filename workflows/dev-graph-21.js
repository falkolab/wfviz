// Tested by test/workflows/gate-template.test.mjs (dry run of a generated script).
//
// args: { judgeCmd, base: '<git commit the run starts from>', priorCategories?: string[] }
//
// Gate per node (AGENTS.md "Development method", graph.md §9), all nodes of the run in parallel:
//  1. guide:<slug>#prep      writes docs/guides/<slug>.md (review method <prep>)
//  2. implement:<slug>       implements the spec in the node's owned paths
//  3. test:<slug>#impl       runs the full suite; counts parsed in code
//  4. review-a / review-b    full review with file, line, input: <= 5 high/medium plus <= 2 low in a
//                            separate list. Node risk "low": reviewer a only. Node risk "high"
//                            (default): both lenses.
//  4b. ui-check:<slug>       only for a node with `ui`: opens wfviz in its own background browser tab,
//                            walks the node's scenario, reports breaks as findings (file "ui", line = step)
//  5. judge:<slug>           codex cli (fallback-claude if it fails). Risk "high": always after the full
//                            review. Risk "low": only when there is a high/medium finding to settle.
//                            Codex usage records are copied to the report (Claude and Codex kept apart).
//  6. guide:<slug>#rule-*    a category approved twice (this run or args.priorCategories) -> rule
//                            in docs/guides/common.md (review method <fix_the_process>)
//  7. fix:<slug>#full        only judge-approved high/medium findings and failing tests
//  8. verify:<slug>#v1..v2   diff-only verification, at most 2 rounds, then blocked
// Test gate: exit 0, fail 0, skipped 0, todo 0, pass > 0, parsed from "# pass N" / "ℹ pass N".
// Labels follow role:unit#tag with the readable node slug as unit (graph.md §9).

const JUDGE_CMD = args && args.judgeCmd
const BASE = args && args.base
if (!JUDGE_CMD || !BASE) throw new Error('args.judgeCmd and args.base are required')
const PRIOR = (args && Array.isArray(args.priorCategories) ? args.priorCategories : []).map((c) => String(c).trim().toLowerCase())
const SUITE = 'node --test test/'
// Model trial (user, 2026-11-09): on a high-risk node reviewer a runs on opus and reviewer b on
// sonnet, same code and rules, so their judge-approved share, unique findings and tokens can be
// compared. Low-risk nodes keep sonnet. The judge wrapper only runs codex: haiku.
const REVIEW_MODEL = { high: { a: 'opus', b: 'sonnet' }, low: { a: 'sonnet', b: 'sonnet' } }

const UNIVERSAL = `wfviz is universal (AGENTS.md, Hard rules): it must work for any user's workflow and must not depend on this project's development method (our roles, labels, node codes, gate, file names); test/integration/universal.test.mjs guards it.`
const COMMON = `Project: wfviz, a local read-only visualizer of Claude Code Dynamic Workflow runs, in the current directory.
Binding: docs/contract.md (contract 2; the change log with evidence is docs/c-rev-proposal.md). Observed formats: sources/event-sources.md, especially its last section "V0 version survey"; per-version tables: sources/format-survey.md.
${UNIVERSAL}
Rules: ES modules, Node >= 20, zero npm dependencies, no network. Write ONLY the files you own. Never run git commit, git stash, git reset or any destructive command. No command longer than 2 minutes. If you start wfviz, always pass --no-open (it must not open a browser) and stop it only by the PID you started (kill <pid>); never pkill, killall or kill by name or port: other wfviz servers on this machine belong to the user. Never use the built-in browser pane tools (mcp__Claude_Browser__*): the pane is the user's; check pages with fetch/curl from a script. Never invent data: a missing value stays missing; do not add handling for formats not observed in sources/event-sources.md.`

const findingOf = (sev) => ({ type: 'object', properties: {
  file: { type: 'string' }, line: { type: 'number' }, input: { type: 'string' }, description: { type: 'string' },
  severity: { type: 'string', enum: sev },
  category: { type: 'string', description: 'one short kebab-case class, e.g. xss, stale-state, invented-value, timer, ordering, layout, weakened-test, leak, method-coupling' } },
  required: ['file', 'line', 'input', 'description', 'severity', 'category'] })
// Blocking findings (high/medium, at most 5) and low ones (at most 2) are separate lists, so lows never use the blocking limit.
const FINDINGS = { type: 'object', properties: {
  findings: { type: 'array', maxItems: 5, items: findingOf(['high', 'medium']) },
  low: { type: 'array', maxItems: 2, items: findingOf(['low']) } }, required: ['findings', 'low'] }
const JUDGE = { type: 'object', properties: { verdict: { type: 'string', enum: ['fix', 'accept'] },
  approved: { type: 'array', items: { type: 'number' } },
  dropped: { type: 'array', items: { type: 'object', properties: { index: { type: 'number' }, reason: { type: 'string' } }, required: ['index', 'reason'] } },
  missed: FINDINGS.properties.findings, contractIssue: { type: 'string' }, engine: { type: 'string' }, note: { type: 'string' } },
  required: ['verdict', 'approved', 'dropped', 'missed', 'contractIssue', 'engine', 'note'] }
// What the judge wrapper returns: the codex verdict plus its usage records, copied as found.
const JUDGE_OUT = { ...JUDGE, properties: { ...JUDGE.properties, usage: { type: 'string' } }, required: [...JUDGE.required, 'usage'] }
// codex cli --output-schema is strict: every object needs additionalProperties:false
const strict = (s) => (s && typeof s === 'object' ? (Array.isArray(s) ? s.map(strict) : Object.fromEntries(Object.entries({ ...s, ...(s.type === 'object' ? { additionalProperties: false } : {}) }).map(([k, v]) => [k, k === 'properties' ? Object.fromEntries(Object.entries(v).map(([pk, pv]) => [pk, strict(pv)])) : strict(v)]))) : s)
const TEST = { type: 'object', properties: { exitCode: { type: 'number' }, outputTail: { type: 'string' } }, required: ['exitCode', 'outputTail'] }
const DONE = { type: 'object', properties: { files: { type: 'array', items: { type: 'string' } }, note: { type: 'string' } }, required: ['files', 'note'] }

const num = (re, s) => { const m = re.exec(s || ''); return m ? Number(m[1]) : null }
const parseTests = (t) => { const o = (t && t.outputTail) || ''; return { exitCode: t ? t.exitCode : null,
  pass: num(/^(?:#|ℹ) pass (\d+)/m, o), fail: num(/^(?:#|ℹ) fail (\d+)/m, o), skipped: num(/^(?:#|ℹ) skipped (\d+)/m, o),
  todo: num(/^(?:#|ℹ) todo (\d+)/m, o), tail: o.slice(-1500) } }
const testsOk = (r) => r.exitCode === 0 && r.fail === 0 && r.skipped === 0 && r.todo === 0 && r.pass > 0
const valid = (f) => f && f.file && Number.isFinite(f.line) && f.line > 0 && f.input && String(f.input).trim()
const serious = (f) => f.severity === 'high' || f.severity === 'medium'
const catOf = (f) => String((f && f.category) || '').trim().toLowerCase()

// Rule agents of parallel nodes all edit docs/guides/common.md: run them one at a time.
const seenCats = [...PRIOR]
let ruleChain = Promise.resolve()
const addRules = (id, n, approvedNow, tag) => {
  const now = approvedNow.map(catOf).filter(Boolean)
  const due = [...new Set(now.filter((c) => now.filter((x) => x === c).length > 1 || seenCats.includes(c)))]
  seenCats.push(...now)
  if (!due.length) return Promise.resolve([])
  const step = ruleChain.then(() => agent(`${COMMON}
A finding category came back: ${JSON.stringify(due)}. Findings in these categories: ${JSON.stringify(approvedNow.filter((f) => due.includes(catOf(f))))}.
Add one rule per category to docs/guides/common.md: one or two sentences that would have prevented these findings, with the category in brackets. Do not repeat a rule already there (sharpen it instead). Write nothing else.`,
    { label: `guide:${id}#rule-${tag}`, phase: 'Guide', schema: DONE, model: 'sonnet' })).then(() => due, () => due)
  ruleChain = step
  return step
}

function gateOf(id, n) {
  const GUIDE = `docs/guides/${id}.md`
  const SPEC = `Node guide: ${GUIDE} (read it; shared rules: docs/guides/common.md).\nSpec:\n${n.spec}`
  const owned = n.owns.join(', '), ownedSp = n.owns.join(' ')

  const runTests = (tag) => agent(`Run exactly this command in the project root and nothing else: ${SUITE}
Return its exit code and the last 3000 characters of combined stdout+stderr as outputTail. Do not fix anything.`,
    { label: `test:${id}#${tag}`, phase: 'Test', schema: TEST, model: 'haiku', effort: 'low' }).then(parseTests)

  const writeGuide = () => agent(`${COMMON}
You write the node guide for node "${n.name}" (unit ${id}) before anyone implements it. Write ${GUIDE} (and create docs/guides/common.md with a one-line header if it does not exist; do not change existing rules there). Write nothing else.
The guide holds: the rules that bind this node, quoted by section from docs/contract.md, AGENTS.md and graph.md §9; the files the node owns (${owned}) and the shared tests it may invalidate (grep test/ for assertions on what the spec changes); traps specific to this spec (where it is easy to invent a value, to couple wfviz to this project's method, to leave a full re-render, to leak a timer or listener, to break escaping); how to check each spec item by hand. At most 80 lines, plain sentences.
Spec:\n${n.spec}`, { label: `guide:${id}#prep`, phase: 'Guide', schema: DONE, model: 'sonnet' })

  const implement = (tag) => agent(`${COMMON}
You implement node ${id} (${n.name}). Files you own: ${owned}.
${SPEC}${tag ? '\nAn earlier implementer of this node stopped without a result; its partial changes may be in the working tree. Read them, keep what is right, finish the spec.' : ''}
Run ${SUITE} and make everything pass honestly. Return the files you wrote or changed.`,
    { label: tag ? `implement:${id}#${tag}` : `implement:${id}`, phase: 'Implement', schema: DONE, model: 'sonnet' })

  const riskOf = n.risk === 'low' ? 'low' : 'high'
  const reviewFull = (who, lens) => agent(`${COMMON}
You are reviewer ${who} for node ${id} (${n.name}). You did not write this code. Assume it is wrong and prove it.
Owned paths: ${owned}. Change since the run started: git diff ${BASE} -- ${ownedSp} ; new files: git status --short -- ${ownedSp}.
${SPEC}
Lens: ${lens}
Report at most 5 high/medium breaks in findings, most important first, and at most 2 low ones in low; each with file, line and a failing input or situation. Severity: high = wrong result or crash in normal use; medium = wrong in a realistic edge case; low = style, wording, unlikely edge. Spend the effort on high/medium. Also report defects in the node guide (${GUIDE}) and any coupling of wfviz to this project's development method. Reject stubs, workaround comments, weakened/skipped/deleted tests, edits outside owned paths. Do not edit files.`,
    { label: `review-${who}:${id}#full`, phase: 'Review', schema: FINDINGS, model: REVIEW_MODEL[riskOf][who] })

  const reviewDiff = (round, items) => agent(`${COMMON}
Verification reviewer for node ${id} (${n.name}). Check ONLY whether these findings are now fixed and whether the fix broke something it touched:
${JSON.stringify(items)}
Look at: git diff ${BASE} -- ${ownedSp} (and new files in git status), and the node guide ${GUIDE}, which the fixer keeps in line with the code. Do not search the rest of the node for new issues. Report remaining or newly introduced breaks only: high/medium in findings (max 5), low in low (max 2). Do not edit files.`,
    { label: `verify:${id}#v${round}`, phase: 'Review', schema: FINDINGS, model: 'sonnet' })

  const judge = (all) => agent(`You coordinate a judge run for node ${id}. Do not judge yourself unless the external judge fails.
1) Write the text between <<<PROMPT and PROMPT>>> to evidence/tmp/judge-${id}.md and this JSON schema to evidence/tmp/judge-schema-${id}.json:
${JSON.stringify(strict(JUDGE))}
2) Run: ${JUDGE_CMD} exec --ephemeral --json -s read-only -m gpt-6.1-sol -C . --output-schema evidence/tmp/judge-schema-${id}.json -o evidence/tmp/judge-${id}.out.json - < evidence/tmp/judge-${id}.md > evidence/tmp/judge-${id}.events.jsonl
3) Return the JSON from evidence/tmp/judge-${id}.out.json unchanged with engine "codex-cli", plus usage: every object named "usage" (or carrying token counts) found in evidence/tmp/judge-${id}.events.jsonl, copied verbatim as a JSON array string with the event type of each; do not add them up or rename fields. If there is none, usage = "unknown: <why>". If the command fails, put its exit code and the last stderr lines in note, judge yourself with the same prompt, engine "fallback-claude", usage "none: fallback".
Never write the command text into any file other than running it.
<<<PROMPT
You are the judge for node ${id} (${n.name}). You check the checkers; you never write code.
${UNIVERSAL} A finding that wfviz depends on this project's method is real.
${SPEC}
Owned paths: ${owned}. Change: git diff ${BASE} -- ${ownedSp}. Contract: docs/contract.md. Observed formats: sources/event-sources.md.
Findings from two reviewers: ${JSON.stringify(all.map((f, i) => ({ i, ...f })))}
Drop findings that are not real, have no failing input, or ask for handling of formats not observed in sources/event-sources.md. Add what both missed (high/medium only, max 3) to missed. approved = indexes for the fixer. verdict "accept" if nothing high/medium must be fixed. If the contract itself is wrong, say so in contractIssue (else empty string) instead of upholding or dropping silently.
PROMPT>>>`, { label: `judge:${id}`, phase: 'Judge', schema: JUDGE_OUT, model: 'haiku', effort: 'low' })

  const uiCheck = () => agent(`${COMMON}
You check node ${id} (${n.name}) in the running page, as a user would. You do not edit files.
Start wfviz from the working tree with the command the scenario gives, else: node bin/wfviz.mjs --no-open --port 0 --idle 0 (always --no-open; read the port it prints), in the background, and stop it when you are done.
Open it ONLY in a new background tab of the built-in browser (mcp__Claude_Browser__tabs_create, then navigate that tabId); never touch, navigate or close any other tab; close your tab at the end. Read the page with read_page / get_page_text / javascript_tool (DOM inspection only); take screenshots only if text cannot answer.
Scenario (each step numbered; check every expected result):
${n.ui.scenario}
Report each step whose result is wrong as a finding: file "ui", line = step number, input = what you did and what the page showed (exact text, values, positions), description = what the spec expects; severity by the same scale (high = wrong in normal use, medium = realistic edge case, low = cosmetic). At most 5 high/medium and 2 low.`,
    { label: `ui-check:${id}`, phase: 'Review', schema: FINDINGS, model: 'sonnet' })

  const fix = (items, tests, tag) => agent(`${COMMON}
You are the fixer for node ${id} (${n.name}). Files you own: ${owned}, and the node guide ${GUIDE}.
${SPEC}
Fix exactly these findings and failing tests; nothing else. Do not weaken, skip or delete tests.
Findings: ${JSON.stringify(items)}
${tests ? `Last test run (${SUITE}): exit ${tests.exitCode}, pass ${tests.pass}, fail ${tests.fail}, skipped ${tests.skipped}, todo ${tests.todo}\n${tests.tail}` : ''}
Then bring ${GUIDE} in line with the code you leave: grep it for every rule, shape, number or claim your fix removed or changed (in the rules, traps, test description and check items) and rewrite each hit to what the code now does; a finding about the guide itself is fixed only in the guide. Do not touch docs/guides/common.md or other guides. List the guide lines you changed in your note.
Run ${SUITE} before finishing. Return the files you changed.`,
    { label: `fix:${id}#${tag}`, phase: 'Fix', schema: DONE, model: 'sonnet' })

  return async () => {
    const report = { node: id, code: n.code || null, rounds: [], low: [], rulesAdded: [] }
    const g = await writeGuide()
    report.guide = g ? g.note : 'guide writer returned nothing'
    // An implementer that returns nothing (a dropped connection, a crash) is retried once; if it fails again the node is
    // blocked at once: reviewers of an unchanged tree find nothing, and the gate must never pass a node that was not built
    // (workflow 16, P1: the implementer died with ECONNRESET and only the review stopped a pass).
    let impl = await implement()
    if (!impl) {
      log(`${id}: implementer returned nothing; retrying once`)
      impl = await implement('retry')
    }
    if (!impl) return { ...report, implement: 'implementer returned nothing twice', status: 'blocked' }
    report.implement = impl.note
    let tests = await runTests('impl')

    const risk = n.risk === 'low' ? 'low' : 'high'
    const checks = [() => reviewFull('a', n.lensA)]
    if (risk === 'high') checks.push(() => reviewFull('b', n.lensB))
    if (n.ui) checks.push(uiCheck)
    const got = await parallel(checks)
    const blocking = (r) => ((r && r.findings) || []).filter(valid).filter(serious)
    const lows = (r) => ((r && r.low) || []).filter(valid)
    const all = got.flatMap(blocking)
    report.low.push(...got.flatMap(lows))
    const names = ['a', risk === 'high' ? 'b' : 'ui', 'ui']
    report.review = { risk, perCheck: got.map((r, i) => ({ check: names[i], model: names[i] === 'ui' ? 'sonnet' : REVIEW_MODEL[risk][names[i]], blocking: blocking(r).length, low: lows(r).length, findings: blocking(r).map((f) => `${f.file}:${f.line} ${f.category}`) })) }
    log(`${id} full review (${risk} risk): ${report.review.perCheck.map((c) => `${c.check} ${c.blocking}+${c.low} low`).join(', ')}`)

    // Risk "high": the judge always runs. Risk "low": only when there is a blocking finding to settle.
    const j = risk === 'high' || all.length ? await judge(all) : null
    const approved = j
      ? [...(j.approved || []).map((i) => all[i]).filter(Boolean).filter(serious), ...((j.missed || []).filter(valid).filter(serious))]
      : all
    report.rulesAdded.push(...await addRules(id, n, approved, 'full'))
    report.judge = j ? { engine: j.engine, verdict: j.verdict, approved: approved.length, dropped: (j.dropped || []).length, contractIssue: j.contractIssue, note: j.note, codexUsage: j.usage } : { skipped: 'risk low and no blocking finding' }
    report.rounds.push({ full: true, findings: all.length, approved: approved.length, tests })
    if (j && j.contractIssue) log(`${id}: judge reports a contract issue: ${j.contractIssue}`)
    if (!approved.length && testsOk(tests)) return { ...report, status: 'pass', tests }

    await fix(approved, testsOk(tests) ? null : tests, 'full')
    tests = await runTests('after-fix')
    let pending = approved.length ? approved : [{ file: 'test/', line: 1, input: 'failing tests', description: 'tests failed', severity: 'high', category: 'tests' }]
    for (let v = 1; v <= 2; v++) {
      const r = await reviewDiff(v, pending)
      const found = ((r && r.findings) || []).filter(valid)
      report.low.push(...((r && r.low) || []).filter(valid))
      const must = found.filter(serious)
      report.rulesAdded.push(...await addRules(id, n, must, `v${v}`))
      report.rounds.push({ verify: v, found: found.length, serious: must.length, tests })
      if (!must.length && testsOk(tests)) return { ...report, status: 'pass', tests }
      if (v === 2) break
      await fix(must, testsOk(tests) ? null : tests, `v${v}`)
      tests = await runTests(`v${v + 1}`)
      pending = must.length ? must : pending
    }
    return { ...report, status: 'blocked', tests }
  }
}

const ids = Object.keys(NODES)
if (!ids.length) throw new Error('no nodes')
const results = await parallel(ids.map((id) => gateOf(id, NODES[id])))
return Object.fromEntries(ids.map((id, i) => [id, results[i] || { node: id, status: 'error', note: 'gate threw or was skipped' }]))
